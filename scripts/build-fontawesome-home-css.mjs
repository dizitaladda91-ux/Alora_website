import fs from 'node:fs/promises';
import path from 'node:path';

const root = process.cwd();
const frontend = path.join(root, 'frontend');
const sourcePath = path.join(frontend, 'styles', 'fontawesome-6.4.0.min.css');
const outputPath = path.join(frontend, 'styles', 'fontawesome-home.min.css');
const usageFiles = [
  'index.html', 'navbar.html', 'footer.html', 'faq-section.html', 'chatbot.html',
  'js/main.js', 'js/include.js', 'js/navbar-interactions.js'
].map(file => path.join(frontend, file));

const [source, ...usage] = await Promise.all([fs.readFile(sourcePath, 'utf8'), ...usageFiles.map(file => fs.readFile(file, 'utf8'))]);
const icons = new Set((usage.join('\n').match(/fa-[a-z0-9-]+/g) || []).filter(name => !['fa-solid', 'fa-regular', 'fa-brands'].includes(name)));
// `fa-shield-check` is a Pro-only name. The existing page used it with the
// Free catalog, where it rendered blank; retain the intended shield visual.
const glyphAliases = new Map([['fa-shield-check', 'fa-shield-halved']]);
const iconRules = [];
const seenRules = new Set();

for (const rule of source.match(/[^{}]+\{[^{}]*\}/g) || []) {
  if (![...icons].some(icon => rule.includes(`.${glyphAliases.get(icon) || icon}:before`))) continue;
  if (!seenRules.has(rule)) {
    seenRules.add(rule);
    iconRules.push(rule);
  }
}

const missing = [...icons].filter(icon => !iconRules.some(rule => rule.includes(`.${glyphAliases.get(icon) || icon}:before`)));
if (missing.length) throw new Error(`Missing Font Awesome glyph rules: ${missing.join(', ')}`);

for (const [alias, target] of glyphAliases) {
  const targetRule = iconRules.find(rule => rule.includes(`.${target}:before`));
  const content = targetRule?.match(/content:("\\[a-f0-9]+")/i)?.[1];
  if (!content) throw new Error(`Unable to resolve glyph alias: ${alias}`);
  iconRules.push(`.${alias}:before{content:${content}}`);
}

const css = `/*! Font Awesome Free 6.4.0 homepage subset. Generated by scripts/build-fontawesome-home-css.mjs */
@font-face{font-family:"Font Awesome 6 Brands";font-style:normal;font-weight:400;font-display:swap;src:url(https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.4.0/webfonts/fa-brands-400.woff2) format("woff2")}@font-face{font-family:"Font Awesome 6 Free";font-style:normal;font-weight:400;font-display:swap;src:url(https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.4.0/webfonts/fa-regular-400.woff2) format("woff2")}@font-face{font-family:"Font Awesome 6 Free";font-style:normal;font-weight:900;font-display:swap;src:url(https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.4.0/webfonts/fa-solid-900.woff2) format("woff2")}.fa{font-family:var(--fa-style-family,"Font Awesome 6 Free");font-weight:var(--fa-style,900)}.fa,.fa-brands,.fa-classic,.fa-regular,.fa-sharp,.fa-solid,.fab,.far,.fas{-moz-osx-font-smoothing:grayscale;-webkit-font-smoothing:antialiased;display:var(--fa-display,inline-block);font-style:normal;font-variant:normal;line-height:1;text-rendering:auto}.fa-classic,.fa-regular,.fa-solid,.far,.fas{font-family:"Font Awesome 6 Free"}.fa-brands,.fab{font-family:"Font Awesome 6 Brands"}${iconRules.join('')}`;

await fs.writeFile(outputPath, css, 'utf8');
console.log(`Built homepage Font Awesome subset: ${icons.size} icons, ${Buffer.byteLength(css)} bytes.`);
